#!/usr/bin/env bash
# Shared settings and helpers for the tiny-models demo. Sourced, not run.
#
# Everything this demo starts is recorded under .runtime/pids and stopped by
# `democtl.sh stop`. Nothing listens on anything but 127.0.0.1.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RT="$ROOT/.runtime"
MODELS="$ROOT/.models"
JOB_NAME="office-hours-005-models"

# Ports, all on 127.0.0.1.
COCKPIT_PORT="${OH5_COCKPIT_PORT:-19500}"
LOCAL_EDGE_PORT="${OH5_LOCAL_EDGE_PORT:-19510}"
CLOUD_EDGE_PORT="${OH5_CLOUD_EDGE_PORT:-19511}"
OLLAMA_PORT="${OH5_OLLAMA_PORT:-18434}"
DIRECT_PORT="${OH5_DIRECT_PORT:-18085}"

# Model 1: Python. Generated by `warm` from scorer/train.py.
SCORER_MODEL="$MODELS/scorer.joblib"

# Model 2: Ollama. This demo runs its own Ollama server on its own port with a
# short keep-alive, so the model leaves memory 30 seconds after the last call
# and stopping the demo stops the server.
OLLAMA_MODEL="${OLLAMA_MODEL:-qwen2.5:0.5b}"
OLLAMA_DEFAULT_URL="http://127.0.0.1:${OLLAMA_PORT}"
OLLAMA_URL="${OLLAMA_URL:-$OLLAMA_DEFAULT_URL}"
OLLAMA_KEEP_ALIVE_SECONDS=30

# Model 3: direct call to an OpenAI-compatible endpoint. By default that is
# llama-server on this machine, serving a GGUF that `warm` downloads. Set
# DIRECT_MODEL_URL (and DIRECT_MODEL_NAME, DIRECT_MODEL_TOKEN) to point the
# same pipeline at any other compatible endpoint; the demo then starts no
# llama-server of its own.
DIRECT_GGUF_URL="${DIRECT_GGUF_URL:-https://huggingface.co/unsloth/SmolLM2-135M-Instruct-GGUF/resolve/main/SmolLM2-135M-Instruct-Q8_0.gguf}"
DIRECT_GGUF="$MODELS/$(basename "$DIRECT_GGUF_URL")"
DIRECT_DEFAULT_URL="http://127.0.0.1:${DIRECT_PORT}/v1/chat/completions"
DIRECT_MODEL_URL="${DIRECT_MODEL_URL:-$DIRECT_DEFAULT_URL}"
DIRECT_MODEL_NAME="${DIRECT_MODEL_NAME:-smollm2-135m}"

OH5_INTERVAL="${OH5_INTERVAL:-2s}"

die() { echo "error: $*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }

need() {
  local tool
  for tool in "$@"; do command -v "$tool" >/dev/null || die "$tool is not on PATH"; done
}

ollama_is_ours() { [[ "$OLLAMA_URL" == "$OLLAMA_DEFAULT_URL" ]]; }
direct_is_ours() { [[ "$DIRECT_MODEL_URL" == "$DIRECT_DEFAULT_URL" ]]; }

port_open() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

# Credentials. Looked up, never copied: OH5_ENV_FILE if set, else a .env beside
# this demo, beside the session, or at the repository root.
find_env_file() {
  local candidate
  for candidate in "${OH5_ENV_FILE:-}" "$ROOT/.env" "$ROOT/../../.env" "$ROOT/../../../../.env"; do
    [[ -n "$candidate" && -f "$candidate" ]] && { (cd "$(dirname "$candidate")" && printf '%s/%s\n' "$(pwd -P)" "$(basename "$candidate")"); return 0; }
  done
  return 1
}

# The office-hours node's data directory: OH5_EDGE_DATA_DIR if set, else the
# .expanso-edge folder that sits next to the .env (see the top-level README).
edge_data_dir() {
  if [[ -n "${OH5_EDGE_DATA_DIR:-}" ]]; then printf '%s\n' "$OH5_EDGE_DATA_DIR"; return; fi
  local env_file
  env_file="$(find_env_file)" || return 1
  printf '%s/.expanso-edge\n' "$(dirname "$env_file")"
}

dotenv_value() {
  awk -v target="$1" '
    /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
    {
      eq = index($0, "="); if (!eq) next
      key = substr($0, 1, eq - 1); gsub(/^[[:space:]]+|[[:space:]]+$/, "", key)
      if (key != target) next
      value = substr($0, eq + 1); gsub(/^[[:space:]]+|[[:space:]]+$/, "", value)
      if ((value ~ /^".*"$/) || (value ~ /^\047.*\047$/)) value = substr(value, 2, length(value) - 2)
      print value; exit
    }
  ' "$2"
}

# Run expanso-cli against Expanso Cloud. The key travels in the environment,
# never on the command line, and an empty config dir keeps any personal
# profile on this machine out of the way.
cloud_cli() {
  local env_file endpoint key
  env_file="$(find_env_file)" || die "no .env found; set OH5_ENV_FILE or see the session README"
  endpoint="$(dotenv_value EXPANSO_ENDPOINT "$env_file")"
  key="$(dotenv_value EXPANSO_API_KEY "$env_file")"
  [[ -n "$endpoint" && "$key" == exp_ak_* ]] || die "$env_file must set EXPANSO_ENDPOINT and EXPANSO_API_KEY"
  mkdir -p "$RT/cli-config"
  EXPANSO_CLI_CONFIG_DIR="$RT/cli-config" EXPANSO_CLI_ENDPOINT="$endpoint" EXPANSO_CLI_AUTH_API_KEY="$key" \
    expanso-cli "$@"
}

# The local edge node in offline mode exposes the same job API on 127.0.0.1.
local_cli() {
  mkdir -p "$RT/cli-config"
  EXPANSO_CLI_CONFIG_DIR="$RT/cli-config" expanso-cli --endpoint "http://127.0.0.1:${LOCAL_EDGE_PORT}" "$@"
}

lane() { [[ -f "$RT/lane" ]] && cat "$RT/lane" || echo none; }

lane_cli() {
  case "$(lane)" in
    cloud) cloud_cli "$@" ;;
    local) local_cli "$@" ;;
    *) die "nothing is up; run just up or just up-offline first" ;;
  esac
}

# expanso-cli appends a "Showing N of M" footer even to JSON; strip it.
json_only() { sed -e '/^Showing /,$d' -e '/^No .* found$/c\
[]'; }

# Start a background process, remember its pid and keep its log.
start_bg() {
  local name="$1"; shift
  mkdir -p "$RT/pids" "$RT/logs"
  (nohup "$@" >"$RT/logs/$name.log" 2>&1 & echo $! >"$RT/pids/$name.pid")
}

pid_of() { [[ -f "$RT/pids/$1.pid" ]] && cat "$RT/pids/$1.pid"; }

alive() {
  local pid
  pid="$(pid_of "$1")" || return 1
  [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null
}

stop_bg() {
  local name="$1" pid
  pid="$(pid_of "$name")" || return 0
  if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
    kill "$pid" 2>/dev/null || true
    for _ in $(seq 1 40); do kill -0 "$pid" 2>/dev/null || break; sleep 0.25; done
    if kill -0 "$pid" 2>/dev/null; then kill -9 "$pid" 2>/dev/null || true; sleep 0.5; fi
    say "stopped $name (pid $pid)"
  fi
  rm -f "$RT/pids/$name.pid"
}

wait_for_url() {
  local url="$1" tries="${2:-80}"
  for _ in $(seq 1 "$tries"); do
    curl -fsS -m 2 "$url" >/dev/null 2>&1 && return 0
    sleep 0.25
  done
  return 1
}

# Environment the edge node needs to resolve the ${...} values in the job.
# Used as: start_bg edge env "${EDGE_ENV[@]}" expanso-edge run ...
edge_env_init() {
  EDGE_ENV=(
    "OH5_DEMO_DIR=$ROOT"
    "OH5_OUTPUT_FILE=$RT/enriched.jsonl"
    "OH5_UV=$(command -v uv)"
    "OH5_INTERVAL=$OH5_INTERVAL"
    "OLLAMA_URL=$OLLAMA_URL"
    "OLLAMA_MODEL=$OLLAMA_MODEL"
    "DIRECT_MODEL_URL=$DIRECT_MODEL_URL"
    "DIRECT_MODEL_NAME=$DIRECT_MODEL_NAME"
    "DIRECT_MODEL_TOKEN=${DIRECT_MODEL_TOKEN:-none}"
  )
}
